import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const modules = ['client/title-hints.mjs', 'client/active-cache.mjs', 'client/directory-picker.mjs', 'client/tooltips.mjs', 'client/section-model.mjs', 'client/sidebar-model.mjs', 'client/sidebar.mjs', 'client/library-model.mjs', 'client/folders.mjs', 'client/list-coalesce.mjs', 'client/app.mjs'];
// These dependency-free source files intentionally use named local imports only.
const strippedImports = [];
const chunks = await Promise.all(modules.map(async file => {
  const source = await readFile(resolve(root, file), 'utf8');
  return `// ${file}\n` + source
    .replace(/^import\s+\{([^}]+)\}\s+from\s+['"]\.\/[^'"]+['"];?\s*$/gm, (_, names) => {
      for (const part of names.split(',')) {
        const name = part.trim().split(/\s+as\s+/).pop().trim();
        if (name) strippedImports.push(name);
      }
      return '';
    })
    .replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, '');
}));
const output = `// dsh-session-library 0.2.11 — generated by scripts/build.mjs\nwindow.__ModuleLoader__.load({id:'dsh-session-library',factory:require=>{\nconst React=require('react');\n${chunks.join('\n\n')}\nreturn {inject:['slots','sessions','workspaces','locale','uiWorkspace','contextMenus','remoteAccess','remote'],apply(ctx){installLibrary(ctx,React)}};\n}});\n`;
// Every stripped local import must resolve inside the concatenated bundle,
// otherwise activation fails in the browser with a bare ReferenceError.
const missing = [...new Set(strippedImports)].filter(name => !new RegExp(`(?:function|const|let|var)\\s+${name}\\b`).test(output));
if (missing.length > 0) {
  console.error(`Build failed: stripped imports missing from bundle: ${missing.join(', ')}`);
  process.exit(1);
}
new vm.Script(output, { filename: 'client.js' });
await mkdir(resolve(root, 'lib'), { recursive: true });
await writeFile(resolve(root, 'lib/client.js'), output);
console.log(`Built lib/client.js (${Buffer.byteLength(output)} bytes)`);
